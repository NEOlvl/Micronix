"""Тесты db_manager: roundtrip, образцы, сырые массивы, импорт архива."""

import os
import pytest

from backend.database.db_manager import (
    DatabaseError, DatabaseManager, record_from_archive,
    resonance_from_record)
from backend.core.calculator.base import ResonanceChannels

ARCHIVE_DIR = os.path.join(os.path.dirname(__file__), '..',
                           'measurement_data')


def make_record(**over):
    rec = {
        'measure_id': 'test001',
        'method_id': 'mfd',
        'title': 'Замер №1',
        'description': 'тестовое измерение',
        'params': {'t': 1.0, 'D': 45.0, 'L0': 80.0},
        'f0': 1.0e10, 'f1': 9.9e9, 'f2': 1.01e10,
        'a0': -35.0, 'q0': 500.0,
        'sweep': {'x': [9e9, 1e10, 1.1e10], 'y': [-5.0, -35.0, -5.0]},
        'samples': [{
            'name': 'Образец А', 'fe': 9.8e9, 'f1e': 9.7e9,
            'f2e': 9.9e9, 'ae': -30.0, 'qe': 49.0,
            'e': 2.5, 'tgo': 0.0025,
            'sweep_y': [-4.0, -30.0, -4.0], 'custom': 'extra',
        }],
    }
    rec.update(over)
    return rec


@pytest.fixture
def db(tmp_path):
    return DatabaseManager(str(tmp_path / 'test.db'))


class TestSaveLoad:
    def test_roundtrip(self, db):
        db.save_measurement(make_record())
        rec = db.load_measurement('test001')
        assert rec['method_id'] == 'mfd'
        assert rec['title'] == 'Замер №1'
        assert rec['params'] == {'t': 1.0, 'D': 45.0, 'L0': 80.0}
        assert rec['f0'] == pytest.approx(1.0e10)
        assert rec['sweep']['x'] == [9e9, 1e10, 1.1e10]
        assert rec['sweep']['y'] == [-5.0, -35.0, -5.0]
        assert rec['created_at'] and rec['updated_at']

    def test_samples_roundtrip(self, db):
        db.save_measurement(make_record())
        s = db.load_measurement('test001')['samples'][0]
        assert s['name'] == 'Образец А'
        assert s['e'] == pytest.approx(2.5)
        assert s['tgo'] == pytest.approx(0.0025)
        assert s['sweep_y'] == [-4.0, -30.0, -4.0]
        assert s['custom'] == 'extra'  # неизвестные поля в extra_json

    def test_upsert_preserves_created(self, db):
        db.save_measurement(make_record())
        first = db.load_measurement('test001')
        db.save_measurement(make_record(title='Новое имя'))
        rec = db.load_measurement('test001')
        assert rec['title'] == 'Новое имя'
        assert rec['created_at'] == first['created_at']
        assert len(rec['samples']) == 1  # старые образцы заменены

    def test_autogenerated_id(self, db):
        mid = db.save_measurement({'method_id': 'so'})
        assert mid and db.load_measurement(mid)['method_id'] == 'so'

    def test_missing_method_id_raises(self, db):
        with pytest.raises(DatabaseError):
            db.save_measurement({'title': 'нет метода'})

    def test_missing_returns_none(self, db):
        assert db.load_measurement('nonexistent') is None


class TestListDelete:
    def test_list_filter(self, db):
        db.save_measurement(make_record(measure_id='a'))
        db.save_measurement(make_record(measure_id='b', method_id='so'))
        assert len(db.list_measurements()) == 2
        only = db.list_measurements(method_id='so')
        assert [m['measure_id'] for m in only] == ['b']

    def test_delete(self, db):
        db.save_measurement(make_record())
        assert db.delete_measurement('test001')
        assert db.load_measurement('test001') is None
        assert not db.delete_measurement('test001')

    def test_delete_cascades_samples(self, db):
        db.save_measurement(make_record())
        db.delete_measurement('test001')
        with db._connect() as con:
            n = con.execute('SELECT COUNT(*) FROM samples').fetchone()[0]
        assert n == 0


class TestArchiveImport:
    @pytest.fixture
    def archive_file(self):
        files = [f for f in os.listdir(ARCHIVE_DIR)
                 if f.endswith('.txt')]
        assert files, 'нет архивных файлов'
        return os.path.join(ARCHIVE_DIR, files[0])

    def test_import_structure(self, archive_file):
        rec = record_from_archive(archive_file)
        assert rec['method_id'] in {'mfch', 'mfd', 'so', 'svchf', 'msr9'}
        assert len(rec['sweep']['x']) > 100
        assert rec['f0'] and rec['f0'] > 1e9
        assert rec['samples'], 'нет образцов'
        # ключи 'data[N][t]' нормализованы
        assert all(not k.startswith('data[')
                   for k in rec['params'])

    def test_import_and_save(self, db, archive_file):
        rec = record_from_archive(archive_file)
        db.save_measurement(rec)
        loaded = db.load_measurement(rec['measure_id'])
        assert loaded['sweep']['x'] == rec['sweep']['x']
        assert len(loaded['samples']) == len(rec['samples'])

    def test_resonance_from_record(self):
        ch = resonance_from_record(make_record())
        assert isinstance(ch, ResonanceChannels)
        assert ch.f0 == pytest.approx(1.0e10)
        assert ch.fe == pytest.approx(9.8e9)


class TestReprocessing:
    """Повторная обработка сохранённых массивов (ТЗ-8)."""

    def test_reprocess_archive(self, db):
        import glob
        for path in glob.glob(os.path.join(ARCHIVE_DIR, '*.txt'))[:10]:
            rec = record_from_archive(path)
            db.save_measurement(rec)
            loaded = db.load_measurement(rec['measure_id'])
            x, y = loaded['sweep']['x'], loaded['sweep']['y']
            assert len(x) == len(y) > 0
            # сырые массивы пригодны для data_processor
            from backend.core.data_processor import extract_resonance_db
            res = extract_resonance_db(x, y)
            assert res['f0'] > 0
